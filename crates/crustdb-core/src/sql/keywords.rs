/// Curated completion keywords for the dialect.
pub fn keywords(kind: DriverKind) -> &'static [&'static str] {
    // Built once; COMMON is shared by both dialect lists.
    static PG: std::sync::LazyLock<Vec<&'static str>> =
        std::sync::LazyLock::new(|| [COMMON, POSTGRES].concat());
    static MY: std::sync::LazyLock<Vec<&'static str>> =
        std::sync::LazyLock::new(|| [COMMON, MYSQL].concat());
    match kind {
        DriverKind::Postgres => &PG,
        DriverKind::Mysql => &MY,
        // ponytail: SQLite borrows the PostgreSQL list; own list when completion feels off.
        DriverKind::Sqlite => &PG,
        // unreachable: no Redis driver is registered; the Capabilities gate (#166) takes over
        DriverKind::Redis => &[],
    }
}
